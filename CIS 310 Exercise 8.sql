--Retrieve Customer ID, Balance, and Available Credit as AVAILABLE_CREDIT (Credit Limit - Balance)
--for all customers where balance is greater than the average balance, 
--as a nested query, or Available credit is positive. Order by available credit descending.
SELECT C.FIRST_NAME AS CUSTFNAME, BALANCE, CREDIT_LIMIT,(CREDIT_LIMIT - BALANCE) AS AVAILABLE_CREDIT, SR.REP_ID, SR.FIRST_NAME AS REPFNAME
	FROM CUSTOMER C INNER JOIN SALES_REP SR ON C.REP_ID = SR.REP_ID
		WHERE C.BALANCE > (SELECT MIN(C.BALANCE)
						FROM CUSTOMER C)
						AND (CREDIT_LIMIT - BALANCE) >= 0
							ORDER BY AVAILABLE_CREDIT DESC;
SELECT * FROM CUSTOMER
WHERE BALANCE > (SELECT AVG(C.BALANCE)FROM CUSTOMER C)
UNION
SELECT * FROM CUSTOMER
WHERE (CREDIT_LIMIT - BALANCE) >= 0;


SELECT CUST_ID, AVG(C.BALANCE) 
						FROM CUSTOMER C
						GROUP BY CUST_ID
						HAVING AVG(C.BALANCE) > 50;

SELECT C.FIRST_NAME AS CUST_FNAME, C.BALANCE,(CREDIT_LIMIT - BALANCE) AS AVAILABLE_CREDIT, SR.REP_ID, SR.FIRST_NAME AS REP_FNAME
	FROM CUSTOMER C INNER JOIN SALES_REP SR ON C.REP_ID = SR.REP_ID
		WHERE C.BALANCE > (SELECT AVG(C.BALANCE) 
						FROM CUSTOMER C)
						OR ((CREDIT_LIMIT - BALANCE) >= 0 
						AND (CREDIT_LIMIT - BALANCE) < 800)
				GROUP BY C.FIRST_NAME, SR.FIRST_NAME, CREDIT_LIMIT, C.BALANCE, SR.REP_ID
					HAVING AVG(C.BALANCE) > 50
						ORDER BY SR.FIRST_NAME, AVAILABLE_CREDIT DESC;


